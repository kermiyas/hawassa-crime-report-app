  final String languageCode;
  AppLocalizations(this.languageCode);

  bool get isAmharic => languageCode == 'am';

  String get(String key) {
    final map = isAmharic ? _am : _en;
    return map[key] ?? _en[key] ?? key;
  }

  String translateRiskLevel(String risk) {
    switch (risk) {
      case 'High Risk':   return get('high_risk');
      case 'Medium Risk': return get('medium_risk');
      case 'Low Risk':    return get('low_risk');
      default:            return risk;
    }
  }

  String translateCrimeType(String crime) {
    switch (crime.toLowerCase()) {
